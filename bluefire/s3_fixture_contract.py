"""Explicit second-generation owned-object lifecycle, not execution authority."""

from __future__ import annotations

import hashlib
import re
from typing import Any, Mapping

from .s3_access_contract import S3AccessError, S3AccessScope, digest, document, exact
from .util import canonical_json_bytes, content_hash

REQUEST_SCHEMA = "bluefire.s3-worker-request.v2"
RESULT_SCHEMA = "bluefire.s3-worker-result.v2"
ENROLLMENT_SCHEMA = "bluefire.s3-fixture-enrollment.v2"
OPERATION_SCHEMA = "bluefire.s3-fixture-operation.v2"
BUCKET_SHAPE = "never_versioned_no_object_lock"
OPERATIONS = {"prepare_fixture", "reconcile_fixture", "cleanup_fixture"}
SEND_LIMITS = {"prepare_fixture": 6, "reconcile_fixture": 5, "cleanup_fixture": 7}
PURPOSES = ("primary", "health")
ERROR_CODES = {"ObjectLockConfigurationNotFoundError", "ConditionalRequestConflict"}
_HEX = re.compile(r"[0-9a-f]{64}", re.ASCII)
_ETAG = re.compile(r'"[A-Za-z0-9._+-]{1,128}"', re.ASCII)


def payload(scope_id: str, purpose: str) -> bytes:
    if not isinstance(scope_id, str) or re.fullmatch(r"s3-[0-9a-f]{32}", scope_id) is None:
        raise S3AccessError("fixture scope identity is invalid")
    if purpose not in PURPOSES:
        raise S3AccessError("fixture purpose is unsupported")
    return (
        canonical_json_bytes(
            {
                "schema_version": "bluefire.s3-generated-fixture.v1",
                "scope_id": scope_id,
                "purpose": purpose,
            }
        )
        + b"\n"
    )


def validate_objects(scope: S3AccessScope) -> None:
    binding = S3AccessScope.from_mapping(scope.to_dict()).to_dict()
    for obj in binding["objects"]:
        raw = payload(binding["scope_id"], obj["purpose"])
        if (
            obj["size_bytes"] != len(raw)
            or obj["sha256"] != "sha256:" + hashlib.sha256(raw).hexdigest()
        ):
            raise S3AccessError("fixture scope does not bind the exact canonical generated bytes")


def enrollment(scope: S3AccessScope, value: Any) -> dict[str, Any]:
    row = document(value)
    exact(
        row,
        {
            "schema_version",
            "scope_digest",
            "generation_digest",
            "exclusive_writer_digest",
            "bucket_shape",
        },
        "fixture enrollment",
    )
    if (
        row["schema_version"] != ENROLLMENT_SCHEMA
        or row["scope_digest"] != scope.digest
        or row["bucket_shape"] != BUCKET_SHAPE
    ):
        raise S3AccessError("fixture enrollment differs from its explicit supported generation")
    digest(row["generation_digest"])
    digest(row["exclusive_writer_digest"])
    validate_objects(scope)
    return row


def etag(value: Any) -> str:
    if not isinstance(value, str) or _ETAG.fullmatch(value) is None:
        raise S3AccessError("fixture conditional identity is unsupported")
    return value


def operation(scope: S3AccessScope, name: str, value: Any) -> dict[str, Any]:
    row = document(value)
    exact(row, {"schema_version", "intent_id", "purpose", "expected_etag"}, "fixture operation")
    if (
        name not in OPERATIONS
        or row["schema_version"] != OPERATION_SCHEMA
        or row["purpose"] not in PURPOSES
    ):
        raise S3AccessError("fixture operation is unsupported")
    if not isinstance(row["intent_id"], str) or _HEX.fullmatch(row["intent_id"]) is None:
        raise S3AccessError("fixture intent identity is invalid")
    if row["expected_etag"] is not None:
        etag(row["expected_etag"])
    if name == "prepare_fixture" and row["expected_etag"] is not None:
        raise S3AccessError("fixture creation cannot replace an existing object")
    validate_objects(scope)
    return row


def selected_object(scope: Mapping[str, Any], fixture: Mapping[str, Any]) -> Mapping[str, Any]:
    return next(obj for obj in scope["objects"] if obj["purpose"] == fixture["purpose"])


def object_metadata(scope: Mapping[str, Any], fixture: Mapping[str, Any]) -> dict[str, str]:
    obj = selected_object(scope, fixture)
    return {
        "bluefire-scope": scope["scope_id"],
        "bluefire-intent": fixture["intent_id"],
        "bluefire-purpose": obj["purpose"],
        "bluefire-sha256": obj["sha256"],
    }


def operation_plan(row: Mapping[str, Any]) -> list[tuple[str, str, str]]:
    plan = [("sts", "GetCallerIdentity", "controller")]
    names = ["GetBucketVersioning", "GetObjectLockConfiguration", "GetObject"]
    if row["operation"] == "prepare_fixture":
        names += ["PutObject", "GetObject"]
    elif row["operation"] == "cleanup_fixture" and row["fixture"]["expected_etag"] is not None:
        names += ["DeleteObject", "GetObject", "ListObjectsV2"]
    else:
        names += ["ListObjectsV2"]
    return plan + [("s3", name, "controller") for name in names]


def observation(row: Mapping[str, Any], state: str, observed_etag: str | None) -> dict[str, Any]:
    fixture = row["fixture"]
    obj = selected_object(row["scope"], fixture)
    return {
        "purpose": fixture["purpose"],
        "intent_id": fixture["intent_id"],
        "state": state,
        "etag": observed_etag,
        "expected_object": dict(obj),
        "bucket_shape": BUCKET_SHAPE,
        "policy_mutated": False,
    }


def validate_observation(row: Mapping[str, Any], value: Any, calls: list[dict[str, Any]]) -> None:
    exact(
        value,
        {
            "purpose",
            "intent_id",
            "state",
            "etag",
            "expected_object",
            "bucket_shape",
            "policy_mutated",
        },
        "fixture observation",
    )
    state = value["state"]
    if state not in ("owned", "absent", "drift") or value != observation(row, state, value["etag"]):
        raise S3AccessError("fixture observation differs from its exact saved intent")
    if type(value["policy_mutated"]) is not bool:
        raise S3AccessError("fixture observation cannot claim policy changes")
    if state == "owned":
        etag(value["etag"])
    elif value["etag"] is not None:
        raise S3AccessError("unowned fixture observation cannot authorize deletion")
    expected_errors = {2: (404, "ObjectLockConfigurationNotFoundError")}
    if row["operation"] == "prepare_fixture":
        if state != "owned":
            raise S3AccessError("fixture preparation lacks an exact owned readback")
        expected_errors[3] = (404, "NoSuchKey")
    elif row["operation"] == "cleanup_fixture":
        if state != "absent":
            raise S3AccessError("fixture cleanup lacks absence readback")
        expected_errors[5 if row["fixture"]["expected_etag"] is not None else 3] = (
            404,
            "NoSuchKey",
        )
    elif state == "absent":
        expected_errors[3] = (404, "NoSuchKey")
    for index, call in enumerate(calls):
        expected = expected_errors.get(index)
        if expected is not None:
            if (call["http_status"], call.get("error_code")) != expected:
                raise S3AccessError("fixture state lacks its exact service observation")
        elif "error_code" in call:
            raise S3AccessError("fixture observation includes an unresolved service refusal")


def authority_digest(scope: S3AccessScope, value: Any) -> str:
    return content_hash(enrollment(scope, value))
